export function pickScenePrompt(mode?: 'disguised' | 'remote' | 'hunter' | 'any'): ScenePrompt {
  if (mode === 'disguised') return pick(SCENE_POOL_DISGUISED);
  if (mode === 'remote')    return pick(SCENE_POOL_REMOTE);
  if (mode === 'hunter')    return pick(SCENE_POOL_HUNTER);
  const r = Math.random();
  if (r < 0.50) return pick(SCENE_POOL_DISGUISED);
  if (r < 0.75) return pick(SCENE_POOL_REMOTE);
  return pick(SCENE_POOL_HUNTER);
}

